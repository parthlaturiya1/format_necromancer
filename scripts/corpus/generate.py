"""Build-time only. Draws our own synthetic 8-bit palette images and writes PCX samples,
Pillow-decoded reference PNGs, and corpus/manifest.json. Deterministic: no clock, no
unseeded randomness. Run: python scripts/corpus/generate.py (Pillow pinned in requirements.txt)."""
import hashlib
import json
import random
from pathlib import Path

import PIL
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
CORPUS = ROOT / "corpus"
SOURCE = "generated by scripts/corpus/generate.py, original"


def palette(kind, seed):
    rng = random.Random(seed)
    p = []
    for i in range(256):
        if kind == "gray":
            p += [i, i, i]
        elif kind == "fire":
            p += [min(255, i * 2), min(255, max(0, i - 64) * 2), max(0, i - 192) * 4]
        elif kind == "ocean":
            p += [i // 4, i // 2, 128 + i // 2]
        else:  # random but seeded
            p += [rng.randrange(256), rng.randrange(256), rng.randrange(256)]
    return p


def img(w, h, pal):
    im = Image.new("P", (w, h), 0)
    im.putpalette(pal)
    return im, ImageDraw.Draw(im)


def hgrad(w, h, pal):  # long horizontal runs per row: run-length friendly
    im, d = img(w, h, pal)
    for y in range(h):
        d.line([(0, y), (w, y)], fill=y * 255 // max(1, h - 1))
    return im


def vgrad(w, h, pal):  # every pixel differs from its neighbour: run-length hostile
    im, d = img(w, h, pal)
    for x in range(w):
        d.line([(x, 0), (x, h)], fill=x * 255 // max(1, w - 1))
    return im


def shapes(w, h, pal):
    im, d = img(w, h, pal)
    d.rectangle([w // 8, h // 8, w * 5 // 8, h * 5 // 8], fill=60)
    d.ellipse([w // 3, h // 3, w * 7 // 8, h * 7 // 8], fill=140)
    d.polygon([(w // 2, 2), (w - 3, h // 2), (w // 2, h - 3), (2, h // 2)], outline=250)
    d.line([(0, 0), (w, h)], fill=200)
    return im


def checker(w, h, pal, cell):
    im, d = img(w, h, pal)
    for y in range(0, h, cell):
        for x in range(0, w, cell):
            d.rectangle([x, y, x + cell - 1, y + cell - 1], fill=((x // cell + y // cell) % 2) * 220 + 20)
    return im


def stripes(w, h, pal, step):
    im, d = img(w, h, pal)
    for x in range(w):
        d.line([(x, 0), (x, h)], fill=(x // step * 37) % 256)
    return im


def text(w, h, pal, msg):
    im, d = img(w, h, pal)
    d.rectangle([0, 0, w, h], fill=30)
    d.text((4, h // 2 - 5), msg, fill=240)
    return im


def rings(w, h, pal):
    im, d = img(w, h, pal)
    for i in range(min(w, h) // 2, 0, -3):
        d.ellipse([w // 2 - i, h // 2 - i, w // 2 + i, h // 2 + i], fill=(i * 7) % 256)
    return im


def diag(w, h, pal):
    im, d = img(w, h, pal)
    for y in range(h):
        for x in range(w):
            im.putpixel((x, y), (x + y) * 255 // (w + h - 2))
    return im


# id, builder. Sizes and palettes vary; widths include odd values (PCX pads scanlines to even).
SAMPLES = [
    ("hgrad-gray-64x48", lambda: hgrad(64, 48, palette("gray", 0))),
    ("vgrad-fire-97x61", lambda: vgrad(97, 61, palette("fire", 0))),
    ("shapes-rand-128x96", lambda: shapes(128, 96, palette("rand", 11))),
    ("checker8-ocean-80x80", lambda: checker(80, 80, palette("ocean", 0), 8)),
    ("checker1-gray-65x33", lambda: checker(65, 33, palette("gray", 0), 1)),
    ("stripes-rand-200x40", lambda: stripes(200, 40, palette("rand", 22), 5)),
    ("text-fire-160x32", lambda: text(160, 32, palette("fire", 0), "FORMAT NECROMANCER")),
    ("rings-rand-111x111", lambda: rings(111, 111, palette("rand", 33))),
    ("diag-ocean-256x16", lambda: diag(256, 16, palette("ocean", 0))),
    ("solid-gray-32x32", lambda: img(32, 32, palette("gray", 0))[0]),
    ("tiny-rand-7x5", lambda: shapes(7, 5, palette("rand", 44))),
]
HELDOUT = ("heldout-01", lambda: rings(150, 90, palette("rand", 99)))


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def rel(p):
    return p.relative_to(ROOT).as_posix()


def main():
    for d in ("samples", "reference", "heldout"):
        (CORPUS / d).mkdir(parents=True, exist_ok=True)
    entries = []
    for sid, build in SAMPLES:
        pcx = CORPUS / "samples" / f"{sid}.pcx"
        build().save(pcx, format="PCX")
        png = CORPUS / "reference" / f"{sid}.png"
        with Image.open(pcx) as dec:
            dec.load()
            dec.save(png, format="PNG", optimize=False)
            w, h = dec.size
        entries.append({
            "id": sid, "path": rel(pcx), "sha256": sha(pcx), "bytes": pcx.stat().st_size,
            "width": w, "height": h, "source": SOURCE, "license": "CC0-1.0",
            "reference": {"path": rel(png), "sha256": sha(png), "tool": f"Pillow {PIL.__version__} PCX decode, saved as PNG"},
            "heldOut": False,
        })
    hp = CORPUS / "heldout" / f"{HELDOUT[0]}.pcx"
    HELDOUT[1]().save(hp, format="PCX")
    manifest = {
        "version": 1,
        "samples": entries,
        "heldOut": [{"path": rel(hp), "sha256": sha(hp), "heldOut": True}],
    }
    (CORPUS / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", newline="\n")
    print(f"wrote {len(entries)} samples + 1 held-out")


if __name__ == "__main__":
    main()
